begin;

create sequence if not exists public.books_id_seq;
create sequence if not exists public.loan_requests_id_seq;
create sequence if not exists public.loans_id_seq;
create sequence if not exists public.locations_id_seq;
create sequence if not exists public.users_id_seq;

create table if not exists public.books (
  id bigint not null default nextval('public.books_id_seq'::regclass),
  isbn text,
  title text not null,
  author text,
  publisher text,
  genre text,
  stock integer default 1,
  rental text default '○'::text,
  memo text,
  created_at timestamp with time zone default now(),
  location_id bigint,
  is_purchase_planned boolean not null default false,
  is_provisional boolean not null default false,
  reserved_state_1 boolean not null default false,
  reserved_state_2 boolean not null default false,
  reserved_state_3 boolean not null default false,
  main_attribute_id bigint
);

create table if not exists public.loan_requests (
  id bigint not null default nextval('public.loan_requests_id_seq'::regclass),
  book_id bigint not null,
  requester_name text,
  requester_contact text,
  message text,
  status text default 'pending'::text,
  created_at timestamp with time zone default now()
);

create table if not exists public.loans (
  id bigint not null default nextval('public.loans_id_seq'::regclass),
  book_id bigint not null,
  user_id bigint not null,
  loan_date timestamp with time zone not null,
  due_date timestamp with time zone,
  returned_at timestamp with time zone,
  created_at timestamp with time zone default now()
);

create table if not exists public.locations (
  id bigint not null default nextval('public.locations_id_seq'::regclass),
  code text not null,
  name text,
  memo text,
  created_at timestamp with time zone default now()
);

create table if not exists public.users (
  id bigint not null default nextval('public.users_id_seq'::regclass),
  name text not null,
  kana text,
  contact text,
  memo text,
  created_at timestamp with time zone default now()
);

alter table public.books
  add column if not exists is_purchase_planned boolean not null default false,
  add column if not exists is_provisional boolean not null default false,
  add column if not exists reserved_state_1 boolean not null default false,
  add column if not exists reserved_state_2 boolean not null default false,
  add column if not exists reserved_state_3 boolean not null default false,
  add column if not exists main_attribute_id bigint;

create table if not exists public.attributes (
  id bigint generated by default as identity primary key,
  name text not null,
  attribute_type text not null check (attribute_type in ('main', 'sub')),
  is_r18 boolean not null default false,
  parent_attribute_id bigint references public.attributes(id) on delete restrict,
  created_at timestamp with time zone default now(),
  constraint attributes_name_type_key unique (name, attribute_type),
  constraint attributes_r18_sub_only check (not is_r18 or attribute_type = 'sub')
);

alter table public.attributes
  add column if not exists parent_attribute_id bigint
  references public.attributes(id) on delete restrict;

create or replace function public.validate_attribute_parent()
returns trigger
language plpgsql
as $$
begin
  if new.attribute_type = 'main' and new.parent_attribute_id is not null then
    raise exception '主属性に親属性は設定できません。';
  end if;

  if new.attribute_type = 'sub' and new.parent_attribute_id is null then
    raise exception '副属性には親となる主属性が必要です。';
  end if;

  if new.parent_attribute_id is not null and not exists (
    select 1
    from public.attributes as parent
    where parent.id = new.parent_attribute_id
      and parent.attribute_type = 'main'
  ) then
    raise exception '副属性の親には主属性を指定してください。';
  end if;

  return new;
end;
$$;

drop trigger if exists attributes_validate_parent on public.attributes;
create trigger attributes_validate_parent
before insert or update of attribute_type, parent_attribute_id
on public.attributes
for each row
execute function public.validate_attribute_parent();

create table if not exists public.book_attributes (
  book_id bigint not null,
  attribute_id bigint not null references public.attributes(id) on delete cascade,
  created_at timestamp with time zone default now(),
  primary key (book_id, attribute_id)
);

grant select on public.attributes, public.book_attributes to anon, authenticated;
grant insert, update, delete on public.attributes, public.book_attributes to authenticated;
grant usage, select on sequence public.attributes_id_seq to authenticated;

alter table public.attributes enable row level security;
alter table public.book_attributes enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'attributes'
      and policyname = 'attributes_public_read'
  ) then
    create policy attributes_public_read on public.attributes
      for select to anon, authenticated using (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'attributes'
      and policyname = 'attributes_authenticated_manage'
  ) then
    create policy attributes_authenticated_manage on public.attributes
      for all to authenticated using (true) with check (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'book_attributes'
      and policyname = 'book_attributes_public_read'
  ) then
    create policy book_attributes_public_read on public.book_attributes
      for select to anon, authenticated using (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'book_attributes'
      and policyname = 'book_attributes_authenticated_manage'
  ) then
    create policy book_attributes_authenticated_manage on public.book_attributes
      for all to authenticated using (true) with check (true);
  end if;
end
$$;

create index if not exists book_attributes_attribute_id_idx
  on public.book_attributes (attribute_id);

create index if not exists books_main_attribute_id_idx
  on public.books (main_attribute_id);

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'books_main_attribute_id_fkey'
      and conrelid = 'public.books'::regclass
  ) then
    alter table public.books
      add constraint books_main_attribute_id_fkey
      foreign key (main_attribute_id) references public.attributes(id)
      on delete set null;
  end if;

  if not exists (
    select 1
    from pg_constraint
    where conname = 'books_pending_state_exclusive'
      and conrelid = 'public.books'::regclass
  ) then
    alter table public.books
      add constraint books_pending_state_exclusive
      check (not (is_purchase_planned and is_provisional));
  end if;
end
$$;

insert into public.attributes (name, attribute_type)
select distinct trim(genre), 'main'
from public.books
where nullif(trim(genre), '') is not null
on conflict (name, attribute_type) do nothing;

insert into public.attributes (name, attribute_type) values
  ('コミック', 'main'),
  ('青年コミック', 'main'),
  ('少年コミック', 'main'),
  ('少女コミック', 'main'),
  ('ワイドコミック', 'main'),
  ('文庫コミック', 'main'),
  ('ライトノベル', 'main'),
  ('文庫', 'main'),
  ('新書', 'main'),
  ('単行本', 'main'),
  ('コンピューター・IT', 'main'),
  ('その他', 'main'),
  ('CD', 'main'),
  ('DVD＆Blu-ray', 'main')
on conflict (name, attribute_type) do nothing;

insert into public.attributes (name, attribute_type, parent_attribute_id)
select '青年コミック', 'sub', id
from public.attributes
where name = 'コミック'
  and attribute_type = 'main'
on conflict (name, attribute_type) do nothing;

update public.attributes as sub
set parent_attribute_id = main.id
from public.attributes as main
where main.name = 'コミック'
  and main.attribute_type = 'main'
  and sub.name = '青年コミック'
  and sub.attribute_type = 'sub'
  and sub.parent_attribute_id is null;

insert into public.attributes (name, attribute_type, is_r18, parent_attribute_id)
select 'R18', 'sub', true, id
from public.attributes
where name = 'コミック'
  and attribute_type = 'main'
on conflict (name, attribute_type) do update
set is_r18 = excluded.is_r18;

update public.books as b
set main_attribute_id = a.id
from public.attributes as a
where a.attribute_type = 'main'
  and a.name = trim(b.genre)
  and b.main_attribute_id is null;

update public.books
set is_purchase_planned = is_purchase_planned
      or memo ~ '^\[\[BOOK_STATE:purchase_planned\]\]',
    is_provisional = is_provisional
      or memo ~ '^\[\[BOOK_STATE:provisional\]\]',
    memo = regexp_replace(
      memo,
      '^\[\[BOOK_STATE:(normal|provisional|purchase_planned)\]\]\n?',
      ''
    )
where memo ~ '^\[\[BOOK_STATE:(normal|provisional|purchase_planned)\]\]';

update public.books
set stock = 0,
    rental = '×'::text
where is_purchase_planned or is_provisional;

commit;
